const prisma = require('../../config/prisma');

const normalizeMetal = (metal) => String(metal || 'gold').trim().toLowerCase();
const normalizePurity = (purity) => String(purity || '').trim().toUpperCase();

const roundCurrency = (num) => {
    return Number((Math.round(num * 100) / 100).toFixed(2));
};

/**
 * Calculate derived purities based on 22K gold base rate:
 * 1. Karat-based (out of 24 parts):
 *    - 24K: (baseRate * 24) / 22 = 14,918.18
 *    - 18K: (baseRate * 18) / 22 = 11,188.64
 *    - 14K: (baseRate * 14) / 22 = 8,702.27
 * 2. Percentage Purity of 24K:
 *    - 99.9 (99.9% fine gold): 24K * 0.999 = 14,903.26 (~14,903)
 *    - 99.5 (99.5% fine gold): 24K * 0.995 = 14,843.59 (~14,843)
 */
const calculateDerivedPurities = (baseRate, effectiveDate) => {
    const b = Number(baseRate);
    if (isNaN(b) || b <= 0) {
        throw new Error('Invalid base rate for 22K gold calculation');
    }

    const rate24kNum = (b * 24) / 22;
    const rate24k = roundCurrency(rate24kNum);
    const rate18k = roundCurrency((b * 18) / 22);
    const rate14k = roundCurrency((b * 14) / 22);
    const rate999 = roundCurrency(rate24kNum * 0.999);
    const rate995 = roundCurrency(rate24kNum * 0.995);

    return [
        { metal: 'gold', purity: '24K', ratePerGram: rate24k, effectiveDate },
        { metal: 'gold', purity: '99.9', ratePerGram: rate999, effectiveDate },
        { metal: 'gold', purity: '99.5', ratePerGram: rate995, effectiveDate },
        { metal: 'gold', purity: '18K', ratePerGram: rate18k, effectiveDate },
        { metal: 'gold', purity: '14K', ratePerGram: rate14k, effectiveDate },
    ];
};

const sortRatesPriority = (a, b) => {
    const isA22K = (a.metal || '').toLowerCase() === 'gold' && (a.purity || '').toUpperCase() === '22K';
    const isB22K = (b.metal || '').toLowerCase() === 'gold' && (b.purity || '').toUpperCase() === '22K';
    if (isA22K && !isB22K) return -1;
    if (!isA22K && isB22K) return 1;

    const isAGold = (a.metal || '').toLowerCase() === 'gold';
    const isBGold = (b.metal || '').toLowerCase() === 'gold';
    if (isAGold && !isBGold) return -1;
    if (!isAGold && isBGold) return 1;

    if (isAGold && isBGold) {
        const order = { '22K': 1, '24K': 2, '99.9': 3, '99.5': 4, '18K': 5, '14K': 6 };
        const orderA = order[(a.purity || '').toUpperCase()] || 99;
        const orderB = order[(b.purity || '').toUpperCase()] || 99;
        return orderA - orderB;
    }

    return (a.metal || '').localeCompare(b.metal || '');
};

/**
 * Update gold rate with strict normalization and auto-generation of derived purities
 */
const updateRate = async (rateData) => {
    const metal = normalizeMetal(rateData.metal);
    const purity = normalizePurity(rateData.purity);
    const ratePerGram = roundCurrency(Number(rateData.ratePerGram));
    const effectiveDate = rateData.effectiveDate || new Date();

    const rate = await prisma.goldRate.create({
        data: {
            metal,
            purity,
            ratePerGram,
            effectiveDate
        }
    });
    
    // Automatically calculate other purities if 22K gold is updated
    if (purity === '22K' && metal === 'gold') {
        const autoGeneratedRates = calculateDerivedPurities(ratePerGram, effectiveDate);
        
        // Insert auto-calculated rates
        await prisma.goldRate.createMany({
            data: autoGeneratedRates
        });
        
        // Sync with replica if requested
        if (rateData.syncWithReplica) {
            await prisma.schemeGoldRate.createMany({
                data: autoGeneratedRates
            });
            await prisma.schemeGoldRate.create({
                data: {
                    metal,
                    purity,
                    ratePerGram,
                    effectiveDate
                }
            });
        }
        
        // Trigger recalculation for all automatically updated purities
        for (const autoRate of autoGeneratedRates) {
             recalculateProductPrices('gold', autoRate.purity).catch(err => {
                 console.error(`Error recalculating product prices for ${autoRate.purity}:`, err);
             });
        }
    } else {
        if (rateData.syncWithReplica) {
            await prisma.schemeGoldRate.create({
                data: {
                    metal,
                    purity,
                    ratePerGram,
                    effectiveDate
                }
            });
        }
    }

    // Trigger mass price recalculation in the background for the original rate
    recalculateProductPrices(rate.metal, rate.purity).catch(err => {
        console.error("Error recalculating product prices after rate update:", err);
    });

    return rate;
};

/**
 * Recalculate prices for all active products matching the metal and purity
 */
const recalculateProductPrices = async (metal, purity) => {
    const productService = require('../product/product.service');
    if (productService.recalculatePricesForMetal) {
        await productService.recalculatePricesForMetal(metal, purity);
    } else {
        console.warn("productService.recalculatePricesForMetal not implemented yet");
    }
};

/**
 * Get latest rate for a metal and purity (case-insensitive & trimmed)
 */
const getLatestRate = async (metal, purity) => {
    const m = normalizeMetal(metal);
    const p = normalizePurity(purity);
    return await prisma.goldRate.findFirst({
        where: {
            metal: { equals: m, mode: 'insensitive' },
            purity: { equals: p, mode: 'insensitive' }
        },
        orderBy: [
            { effectiveDate: 'desc' },
            { createdAt: 'desc' }
        ]
    });
};

/**
 * Get all current rates:
 * Guarantees exactly ONE record per (metal, purity) combination.
 */
const getCurrentRates = async () => {
    const allRates = await prisma.goldRate.findMany({
        orderBy: [
            { effectiveDate: 'desc' },
            { createdAt: 'desc' }
        ]
    });

    const uniqueMap = new Map();
    for (const r of allRates) {
        const metal = normalizeMetal(r.metal);
        const purity = normalizePurity(r.purity);
        const key = `${metal}_${purity}`;
        if (!uniqueMap.has(key)) {
            uniqueMap.set(key, {
                ...r,
                metal,
                purity,
                ratePerGram: roundCurrency(Number(r.ratePerGram))
            });
        }
    }

    const currentRates = Array.from(uniqueMap.values());
    return currentRates.sort(sortRatesPriority);
};

/**
 * Delete all rates for a specific metal and purity case-insensitively
 */
const deleteRate = async (metal, purity) => {
    const m = normalizeMetal(metal);
    const p = normalizePurity(purity);
    return await prisma.goldRate.deleteMany({
        where: {
            metal: { equals: m, mode: 'insensitive' },
            purity: { equals: p, mode: 'insensitive' }
        }
    });
};

/**
 * Update Scheme gold rate explicitly
 */
const updateSchemeRate = async (rateData) => {
    const metal = normalizeMetal(rateData.metal);
    const purity = normalizePurity(rateData.purity);
    const ratePerGram = roundCurrency(Number(rateData.ratePerGram));
    const effectiveDate = rateData.effectiveDate || new Date();

    const rate = await prisma.schemeGoldRate.create({
        data: {
            metal,
            purity,
            ratePerGram,
            effectiveDate
        }
    });

    if (purity === '22K' && metal === 'gold') {
        const autoGeneratedRates = calculateDerivedPurities(ratePerGram, effectiveDate);
        await prisma.schemeGoldRate.createMany({
            data: autoGeneratedRates
        });
    }

    return rate;
};

/**
 * Get all current Scheme rates:
 * Guarantees exactly ONE record per (metal, purity) combination.
 */
const getSchemeCurrentRates = async () => {
    if (!prisma.schemeGoldRate) {
        return getCurrentRates();
    }

    const allRates = await prisma.schemeGoldRate.findMany({
        orderBy: [
            { effectiveDate: 'desc' },
            { createdAt: 'desc' }
        ]
    });

    const uniqueMap = new Map();
    for (const r of allRates) {
        const metal = normalizeMetal(r.metal);
        const purity = normalizePurity(r.purity);
        const key = `${metal}_${purity}`;
        if (!uniqueMap.has(key)) {
            uniqueMap.set(key, {
                ...r,
                metal,
                purity,
                ratePerGram: roundCurrency(Number(r.ratePerGram))
            });
        }
    }

    const currentRates = Array.from(uniqueMap.values());
    return currentRates.sort(sortRatesPriority);
};

const deleteSchemeRate = async (metal, purity) => {
    const m = normalizeMetal(metal);
    const p = normalizePurity(purity);
    return await prisma.schemeGoldRate.deleteMany({
        where: {
            metal: { equals: m, mode: 'insensitive' },
            purity: { equals: p, mode: 'insensitive' }
        }
    });
};

